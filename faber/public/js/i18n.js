  const LANGS = ['tr', 'en', 'ru', 'az'];
  const NAMES = { tr: 'Türkçe', en: 'English', ru: 'Русский', az: 'Azərbaycanca' };
  let lang = 'tr';
  try {
    const saved = localStorage.getItem('faber_lang');
    if (saved && DICT[saved]) lang = saved;
  } catch (e) {}

  function t(key, args) {
    let s = DICT[lang][key];
    if (s === undefined) s = DICT.en[key];
    if (s === undefined) return key;
    if (args) for (const k in args) s = s.split('{' + k + '}').join(String(args[k]));
    return s;
  }
  function setLang(l) {
    if (!DICT[l]) return;
    lang = l;
    try { localStorage.setItem('faber_lang', l); } catch (e) {}
    document.documentElement.lang = l;
    applyStatic();
    document.dispatchEvent(new CustomEvent('langchange', { detail: l }));
  }
  function applyStatic(root) {
    (root || document).querySelectorAll('[data-i18n]').forEach(el => {
      el.textContent = t(el.getAttribute('data-i18n'));
    });
    (root || document).querySelectorAll('[data-i18n-ph]').forEach(el => {
      el.setAttribute('placeholder', t(el.getAttribute('data-i18n-ph')));
    });
    (root || document).querySelectorAll('[data-i18n-title]').forEach(el => {
      el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
    });
  }
  window.I18N = { t, setLang, applyStatic, get lang() { return lang; }, LANGS, NAMES };
